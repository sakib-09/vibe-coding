/*
 * test.js — unit tests for LoadLine's pure logic.
 * Run: node test.js
 *
 * The logic lives in the FIRST <script> block of index.html and is
 * browser-free, so we extract it, run it in a VM sandbox, and assert
 * against the exported __llaLogic surface.
 */
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');

function countTag(tag) {
  const re = new RegExp('<' + tag + '[\\s>]', 'g');
  return (html.match(re) || []).length;
}
let passed = 0, failed = 0;
function ok(cond, name) {
  if (cond) { passed++; console.log('  ok - ' + name); }
  else { failed++; console.error('  FAIL - ' + name); }
}

// 1. document sanity
ok(countTag('html') === 1, 'single <html>');
ok(countTag('body') === 1, 'single <body>');
ok((html.match(/<\/script>/g) || []).length === 2, 'two script blocks (logic + UI)');
ok(html.includes('id="dropZone"') && html.includes('id="fileInput"') &&
   html.includes('id="sampleBtn"') && html.includes('id="results"') &&
   html.includes('id="summaryCards"') && html.includes('id="insightsList"') &&
   html.includes('id="wfRows"') && html.includes('id="reqTableBody"') &&
   html.includes('id="copyBtn"') && html.includes('id="jsonBtn"') &&
   html.includes('id="csvBtn"') && html.includes('id="reqSearch"'),
   'key element ids present');
ok(!/Built by Muse|Muse AI|generated by|AI assistant|anthropic/i.test(html), 'no AI attribution in html');

// 2. extract the logic script and run it in a sandbox
const m = html.match(/<script>([\s\S]*?)<\/script>/);
if (!m) { console.error('FAIL: no logic script block found'); process.exit(1); }
const sandbox = { console };
vm.createContext(sandbox);
vm.runInContext(m[1], sandbox);
const L = sandbox.__llaLogic;
ok(!!L, 'logic exported as __llaLogic');

// 3. fixture: 16-entry HAR mirroring the in-app sample (every insight fires)
let _t = 0;
const BASE = Date.UTC(2026, 9, 13, 14, 0, 0);
function mk(o) {
  _t += 180;
  const resH = (o.resH || []).map(p => ({ name: p[0], value: p[1] }));
  return {
    startedDateTime: new Date(BASE + _t).toISOString(),
    time: o.ms,
    request: { method: o.method, url: o.url, headers: [] },
    response: {
      status: o.status, statusText: o.statusText, headers: resH,
      content: { size: o.size, mimeType: o.mime },
      bodySize: o.size, redirectURL: o.redirect || ''
    },
    timings: { blocked: 2, dns: 5, ssl: -1, connect: 12, send: 3, wait: Math.max(1, o.ms - 40), receive: 18 },
    _resourceType: o.rt || ''
  };
}
const entries = [
  mk({ method: 'GET', url: 'https://shop.example.com/', status: 200, statusText: 'OK', mime: 'text/html', size: 24576, ms: 210, rt: 'document', resH: [['Cache-Control', 'max-age=60'], ['Content-Encoding', 'gzip']] }),
  mk({ method: 'GET', url: 'https://shop.example.com/app.js', status: 200, statusText: 'OK', mime: 'application/javascript', size: 92160, ms: 340, rt: 'script' }),
  mk({ method: 'GET', url: 'https://shop.example.com/styles.css', status: 200, statusText: 'OK', mime: 'text/css', size: 38912, ms: 120, rt: 'stylesheet', resH: [['Cache-Control', 'max-age=86400'], ['Content-Encoding', 'gzip']] }),
  mk({ method: 'GET', url: 'https://shop.example.com/logo.png', status: 200, statusText: 'OK', mime: 'image/png', size: 49152, ms: 95, rt: 'image' }),
  mk({ method: 'GET', url: 'https://shop.example.com/missing-image.png', status: 404, statusText: 'Not Found', mime: 'text/html', size: 512, ms: 86, rt: 'image' }),
  mk({ method: 'POST', url: 'https://shop.example.com/api/checkout', status: 500, statusText: 'Internal Server Error', mime: 'application/json', size: 348, ms: 1230, rt: 'xhr' }),
  mk({ method: 'GET', url: 'https://shop.example.com/api/search?q=red+shoes', status: 200, statusText: 'OK', mime: 'application/json', size: 12288, ms: 3400, rt: 'xhr', resH: [['Content-Encoding', 'gzip']] }),
  mk({ method: 'GET', url: 'https://shop.example.com/videos/hero.mp4', status: 200, statusText: 'OK', mime: 'video/mp4', size: 2411725, ms: 1800, rt: 'media' }),
  mk({ method: 'POST', url: 'https://shop.example.com/analytics', status: 204, statusText: 'No Content', mime: 'text/plain', size: 0, ms: 45, rt: 'xhr' }),
  mk({ method: 'POST', url: 'https://shop.example.com/analytics', status: 204, statusText: 'No Content', mime: 'text/plain', size: 0, ms: 52, rt: 'xhr' }),
  mk({ method: 'GET', url: 'http://cdn.example.com/banner.jpg', status: 200, statusText: 'OK', mime: 'image/jpeg', size: 122880, ms: 230, rt: 'image', resH: [['Cache-Control', 'max-age=3600']] }),
  mk({ method: 'GET', url: 'https://shop.example.com/fonts/brand.woff2', status: 200, statusText: 'OK', mime: 'font/woff2', size: 28672, ms: 140, rt: 'font', resH: [['ETag', '"abc123"']] }),
  mk({ method: 'GET', url: 'https://shop.example.com/old-promo', status: 301, statusText: 'Moved Permanently', mime: 'text/html', size: 300, ms: 62, rt: 'other', redirect: 'https://shop.example.com/new-promo' }),
  mk({ method: 'GET', url: 'https://shop.example.com/new-promo', status: 302, statusText: 'Found', mime: 'text/html', size: 310, ms: 58, rt: 'other', redirect: 'https://shop.example.com/deals' }),
  mk({ method: 'GET', url: 'https://shop.example.com/deals', status: 301, statusText: 'Moved Permanently', mime: 'text/html', size: 305, ms: 71, rt: 'other', redirect: 'https://shop.example.com/offers' }),
  mk({ method: 'GET', url: 'https://shop.example.com/offers', status: 200, statusText: 'OK', mime: 'text/html', size: 18300, ms: 190, rt: 'document', resH: [['Cache-Control', 'max-age=300'], ['Content-Encoding', 'gzip']] })
];
const harText = JSON.stringify({ log: { pages: [{ id: 'p1', title: 'Shop' }], entries } });

// 4. parseHar
let r = L.parseHar(harText);
ok(r.ok === true && r.entries.length === 16 && r.pages.length === 1, 'valid HAR parses with pages+entries');
ok(L.parseHar('nope not json').ok === false && /not valid JSON/.test(L.parseHar('nope not json').error), 'invalid JSON -> friendly error');
ok(L.parseHar('{"foo":1}').ok === false && /log\.entries/.test(L.parseHar('{"foo":1}').error), 'missing entries -> friendly error');
ok(L.parseHar(JSON.stringify(entries)).ok === true, 'raw entries array tolerated');
ok(L.parseHar(JSON.stringify({ log: { entries } })).ok === true, 'bare log wrapper tolerated');

// 5. entrySummary edge cases
const e1 = L.entrySummary(mk({ method: 'get', url: 'https://a.com/x.png', status: 200, statusText: 'OK', mime: 'image/png', size: 100, ms: 10 }));
ok(e1.timings.ssl === 0 && e1.timings.dns === 5, '-1 timing values become 0');
const e2 = L.entrySummary({ request: { method: 'POST', url: 'https://a.com/' }, response: { headers: [], content: { size: -1 } } });
ok(e2.status === 0 && e2.timeMs === 0, 'missing status -> 0, missing time -> 0');
ok(e2.sizeBytes === 0, 'size -1 treated as 0');
const e3 = L.entrySummary({ request: { url: 'https://a.com/big' }, response: { status: 200, content: { size: -1 }, bodySize: 4096 } });
ok(e3.sizeBytes === 4096, 'falls back to bodySize when content.size is -1');
ok(e1.method === 'GET' && e1.host === 'a.com' && e1.path === '/x.png', 'method uppercased, host/path parsed');

// 6. summarize
const sm = L.summarize(entries, 'Shop');
ok(sm.count === 16 && sm.failed === 2 && sm.slow === 1, 'counts: 16 requests, 2 failed, 1 slow');
ok(sm.slowest.ms === 3400 && /api\/search/.test(sm.slowest.url), 'slowest request identified');
ok(sm.largest.bytes === 2411725 && /hero\.mp4/.test(sm.largest.url), 'largest request identified');
ok(sm.byType.xhr === 4 && sm.byType.img === 3 && sm.byType.doc === 2, 'type buckets correct');
ok(sm.totalBytes > 2000000 && sm.totalMs > 0, 'totals computed');
const smEmpty = L.summarize([], 'x');
ok(smEmpty.count === 0 && smEmpty.totalMs === 0, 'empty input safe');

// 7. every insight type fires on the fixture
const ins = L.findInsights(entries, 'https://shop.example.com/');
const has = (sev, re) => ins.some(i => i.severity === sev && re.test(i.title));
ok(has('error', /Failed request/) && ins.filter(i => i.severity === 'error' && /Failed request/.test(i.title)).length === 2, 'failed requests -> 2 errors');
ok(has('warn', /Slow request/) && /3\.4 s/.test(ins.find(i => /Slow request/.test(i.title)).title), 'slow request -> warn');
ok(has('warn', /Large download/) && /2\.3 MB/.test(ins.find(i => /Large download/.test(i.title)).title), '1 MB+ response -> warn');
ok(has('info', /Duplicate requests/) && /2×/.test(ins.find(i => /Duplicate requests/.test(i.title)).title), 'duplicate pings -> info');
ok(has('error', /Mixed content/), 'http resource on https page -> error');
ok(has('warn', /no cache headers/), 'uncached static assets -> warn');
ok(has('info', /uncompressed/) && /app\.js/.test(ins.find(i => /uncompressed/.test(i.title)).detail), 'uncompressed 90KB js -> info');
ok(has('info', /redirect chain/) && /3 redirects/.test(ins.find(i => /redirect chain/.test(i.title)).title), '3-hop redirect chain -> info');
const insHttp = L.findInsights(entries, 'http://shop.example.com/');
ok(!insHttp.some(i => /Mixed content/.test(i.title)), 'no mixed-content flag when the page itself is http');
ok(L.findInsights([], 'https://x.com/').length === 0, 'empty input -> no insights');

// 8. helpers
ok(L.formatBytes(0) === '0 B' && L.formatBytes(1024) === '1.0 KB' &&
   L.formatBytes(92160) === '90.0 KB' && L.formatBytes(2411725) === '2.3 MB',
   'formatBytes outputs');
ok(L.formatMs(86) === '86 ms' && L.formatMs(1230) === '1.2 s' &&
   L.formatMs(3400) === '3.4 s', 'formatMs outputs');
ok(L.escapeHtml('<b>&"\'') === '&lt;b&gt;&amp;&quot;&#39;', 'html escaping');

// 9. text summary + csv
const analysis = L.buildAnalysis(entries, 'Shop', 'https://shop.example.com/');
const txt = L.textSummary(analysis);
ok(txt.includes('Requests: 16') && txt.includes('Failed: 2'), 'text summary has headline counts');
ok(txt.includes('Failed requests:') && txt.includes('[404]') && txt.includes('[500]'), 'text summary lists failures');
ok(txt.includes('Slow requests') && txt.includes('3.4 s'), 'text summary lists slow requests');
ok(txt.includes('[ERROR]') && txt.includes('What to tell the user:'), 'text summary has insights + advice line');
const rows = L.csvRows(analysis);
ok(rows[0].join(',') === 'method,status,host,path,type,size_bytes,time_ms', 'csv header row');
ok(rows.length === 17 && rows[1][0] === 'GET' && rows[1][2] === 'shop.example.com' &&
   rows[6][1] === 500 && rows[7][4] === 'xhr', 'csv data rows correct');

// 10. waterfall geometry
const wf = L.buildWaterfall(entries);
ok(wf.length === 16 && wf[0].startOffsetMs === 0 && wf.every(w => w.endOffsetMs >= w.startOffsetMs),
   'waterfall offsets relative to first request');

console.log('\n' + passed + ' passed, ' + failed + ' failed');
process.exit(failed ? 1 : 0);
