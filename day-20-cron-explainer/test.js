/*
 * test.js — unit tests for CronLens' pure logic.
 * Run: node test.js
 *
 * The logic lives in the FIRST <script> block of index.html and is
 * browser-free, so we extract it, run it in a VM sandbox, and assert
 * against the exported __cronLogic surface.
 */
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');

function countTag(tag) {
  const re = new RegExp('<' + tag + '[\\s>]', 'g');
  return (html.match(re) || []).length;
}
let passed = 0, failed = 0;
function ok(cond, name) {
  if (cond) { passed++; console.log('  ok - ' + name); }
  else { failed++; console.error('  FAIL - ' + name); }
}
function throwsWith(fn, re, name) {
  try { fn(); ok(false, name + ' (no error thrown)'); }
  catch (e) { ok(re.test(e.message), name + ' [' + e.message + ']'); }
}

// 1. document sanity
ok(countTag('html') === 1, 'single <html>');
ok(countTag('body') === 1, 'single <body>');
ok((html.match(/<\/script>/g) || []).length === 2, 'two script blocks (logic + UI)');
ok(html.includes('id="expr"') && html.includes('id="explainBtn"') &&
   html.includes('id="descOut"') && html.includes('id="runsOut"') &&
   html.includes('id="fieldsOut"') && html.includes('id="copyBtn"') &&
   html.includes('id="fromInput"') && html.includes('id="countSelect"'),
   'key element ids present');
ok(!/Built by Muse|Muse AI|generated by|AI assistant|anthropic/i.test(html), 'no AI attribution in html');

// 2. extract the logic script and run it in a sandbox
const m = html.match(/<script>([\s\S]*?)<\/script>/);
if (!m) { console.error('FAIL: no logic script block found'); process.exit(1); }
const sandbox = { console };
vm.createContext(sandbox);
vm.runInContext(m[1], sandbox);
const L = sandbox.__cronLogic;
ok(!!L, 'logic exported as __cronLogic');

// helper: local date (tests must not depend on the VM timezone name, but local
// construction is consistent for both logic and expectations)
function D(y, mo, d, h, mi, s) { return new Date(y, mo - 1, d, h || 0, mi || 0, s || 0); }

// 3. parsing basics
let c = L.parseCron('0 2 * * *');
ok(c.fields.minute.has(2) === false && c.fields.hour.has(2) && c.fields.minute.has(0),
   'simple daily schedule parses');
ok(c.hasSeconds === false && !c.reboot, '5-field flags');
ok(c.restricted.minute && c.restricted.hour && !c.restricted.dom &&
   !c.restricted.month && !c.restricted.dow, 'restricted flags correct');

c = L.parseCron('*/15 * * * *');
ok(c.fields.minute.size === 4 && c.fields.minute.has(45), '*/15 expands to 0,15,30,45');

c = L.parseCron('0 9 * * MON-FRI');
ok(c.fields.dow.size === 5 && c.fields.dow.has(1) && c.fields.dow.has(5) && !c.fields.dow.has(0),
   'MON-FRI names parse');

c = L.parseCron('0 0 * * 7');
ok(c.fields.dow.has(0) && !c.fields.dow.has(7), 'dow 7 normalised to Sunday');

c = L.parseCron('0 30 2 * * *');
ok(c.hasSeconds && c.fields.second.has(0) && c.fields.minute.has(30), '6-field with seconds parses');

c = L.parseCron('@daily');
const c2 = L.parseCron('0 0 * * *');
ok(JSON.stringify([...c.fields.minute]) === JSON.stringify([...c2.fields.minute]) &&
   JSON.stringify([...c.fields.hour]) === JSON.stringify([...c2.fields.hour]),
   '@daily expands like 0 0 * * *');
ok(L.parseCron('@reboot').reboot === true, '@reboot flag');

c = L.parseCron('5/20 9-17 1,15 JAN-MAR *');
ok(c.fields.minute.has(5) && c.fields.minute.has(25) && c.fields.minute.has(45) &&
   !c.fields.minute.has(44),
   'value/step form 5/20 -> 5,25,45');
ok(c.fields.hour.has(9) && c.fields.hour.has(17), 'hour range');
ok(c.fields.dom.has(1) && c.fields.dom.has(15), 'dom list');
ok(c.fields.month.has(1) && c.fields.month.has(3) && !c.fields.month.has(4),
   'JAN-MAR name range');

// 4. validation errors
throwsWith(() => L.parseCron('0 2 * *'), /5 fields/, '4 fields rejected');
throwsWith(() => L.parseCron('0 2 * * * * *'), /6 with seconds/, '7 fields rejected');
throwsWith(() => L.parseCron('61 * * * *'), /between 0 and 59/, 'minute 61 rejected');
throwsWith(() => L.parseCron('0 25 * * *'), /between 0 and 23/, 'hour 25 rejected');
throwsWith(() => L.parseCron('*/0 * * * *'), /at least 1/, 'step 0 rejected');
throwsWith(() => L.parseCron('5-2 * * * *'), /backwards/, 'backwards range rejected');
throwsWith(() => L.parseCron('0 0 L * *'), /"L"/, 'L gives friendly unsupported error');
throwsWith(() => L.parseCron('0 0 * * FUNDAY'), /not a valid day of week/, 'bad name rejected');
throwsWith(() => L.parseCron(''), /Enter a cron expression/, 'empty input rejected');
throwsWith(() => L.parseCron('0 2 * * *; rm'), /Invalid character/, 'shell metachar rejected');

// 5. matching semantics (Vixie OR for dom/dow)
// 2026-10-14 is a Wednesday.
ok(L.matches(D(2026, 10, 14, 2, 0), L.parseCron('0 2 * * *')), 'daily match');
ok(!L.matches(D(2026, 10, 14, 3, 0), L.parseCron('0 2 * * *')), 'daily non-match');
c = L.parseCron('0 0 1 * 0'); // 1st of month OR Sunday
ok(L.matches(D(2026, 10, 18, 0, 0), c), 'dow branch of OR fires (Sun Oct 18)');
ok(L.matches(D(2026, 11, 1, 0, 0), c), 'dom branch of OR fires (Nov 1)');
ok(!L.matches(D(2026, 10, 14, 0, 0), c), 'neither branch -> no fire (Wed Oct 14)');
c = L.parseCron('0 0 1 * *');
ok(L.matches(D(2026, 11, 1, 0, 0), c) && !L.matches(D(2026, 10, 18, 0, 0), c),
   'dom-only ignores day of week');

// 6. nextRuns
let runs = L.nextRuns(L.parseCron('0 2 * * *'), D(2026, 10, 14, 12, 0), 3);
ok(runs.length === 3 && runs[0].getTime() === D(2026, 10, 15, 2, 0).getTime() &&
   runs[1].getTime() === D(2026, 10, 16, 2, 0).getTime(), 'daily next runs');

runs = L.nextRuns(L.parseCron('0 9 * * MON-FRI'), D(2026, 10, 14, 12, 0), 2); // Wed
ok(runs[0].getTime() === D(2026, 10, 15, 9, 0).getTime(), 'weekday schedule skips to Thu');

runs = L.nextRuns(L.parseCron('0 9 * * MON-FRI'), D(2026, 10, 16, 18, 0), 1); // Fri evening
ok(runs[0].getTime() === D(2026, 10, 19, 9, 0).getTime(), 'weekday schedule skips weekend to Mon');

runs = L.nextRuns(L.parseCron('30 2 1 * *'), D(2026, 10, 14, 12, 0), 1);
ok(runs[0].getTime() === D(2026, 11, 1, 2, 30).getTime(), 'monthly on the 1st');

runs = L.nextRuns(L.parseCron('0 0 1 * 0'), D(2026, 10, 14, 12, 0), 1);
ok(runs[0].getTime() === D(2026, 10, 18, 0, 0).getTime(), 'OR schedule picks nearer branch (Sunday)');

runs = L.nextRuns(L.parseCron('0 0 29 2 *'), D(2026, 10, 14, 12, 0), 1);
ok(runs.length === 1 && runs[0].getFullYear() === 2028 && runs[0].getMonth() === 1 &&
   runs[0].getDate() === 29, 'Feb 29 waits for leap year (2028)');

runs = L.nextRuns(L.parseCron('*/5 * * * *'), D(2026, 10, 14, 12, 3), 2);
ok(runs[0].getTime() === D(2026, 10, 14, 12, 5).getTime() &&
   runs[1].getTime() === D(2026, 10, 14, 12, 10).getTime(), '*/5 steps from mid-interval');

runs = L.nextRuns(L.parseCron('0 2 * * *'), D(2026, 10, 15, 2, 0), 1);
ok(runs[0].getTime() === D(2026, 10, 16, 2, 0).getTime(), 'next runs are strictly after "from"');

// 7. countRunsIn
ok(L.countRunsIn(L.parseCron('0 * * * *'), D(2026, 10, 14, 0, 0), 7) === 168,
   'hourly -> 168 runs in 7 days');
ok(L.countRunsIn(L.parseCron('0 9 * * MON-FRI'), D(2026, 10, 12, 0, 0), 7) === 5,
   'weekday 9am -> 5 runs in a Mon-Sun week');

// 8. describe()
function hasDesc(expr, re, name) {
  const d = L.describe(L.parseCron(expr));
  ok(re.test(d), name + ' [' + d + ']');
}
hasDesc('0 2 * * *', /^At 02:00\./, 'daily 2am');
hasDesc('*/15 * * * *', /Every 15 minutes\./, 'every-15-minutes phrasing');
hasDesc('* * * * *', /Every minute\./, 'every minute phrasing');
hasDesc('0 9 * * MON-FRI', /Monday.*Friday|Monday-Friday/, 'weekday range names');
hasDesc('0 0 1 * *', /1st of the month/, 'ordinal day of month');
hasDesc('0 0 1 * 0', /either one triggers it/, 'OR gotcha called out');
hasDesc('30 2 * * 6', /Saturday/, 'dow name in description');
hasDesc('0 0 1 1 *', /January/, 'month name in description');
hasDesc('0 30 2 * * *', /02:30:00/, 'seconds folded into time');
ok(L.describe(L.parseCron('@reboot')).includes('(re)boots'), '@reboot description');

// 9. tips
let tips = L.getTips(L.parseCron('0 0 1 * 0'));
ok(tips.some(t => /OR-ed/.test(t)), 'OR tip present');
tips = L.getTips(L.parseCron('* * * * *'));
ok(tips.some(t => /every single minute/.test(t)), 'every-minute warning');
tips = L.getTips(L.parseCron('0 30 2 * * *'));
ok(tips.some(t => /6-field/.test(t)), 'seconds portability tip');
tips = L.getTips(L.parseCron('0 0 29 2 *'));
ok(tips.some(t => /leap years/.test(t)), 'feb 29 tip');
tips = L.getTips(L.parseCron('0 2 * * *'));
ok(tips.length === 0, 'plain daily schedule has no tips');

// 10. helpers
ok(L.ordinal(1) === '1st' && L.ordinal(2) === '2nd' && L.ordinal(3) === '3rd' &&
   L.ordinal(4) === '4th' && L.ordinal(11) === '11th' && L.ordinal(21) === '21st',
   'ordinals');
ok(L.listJoin(['a']) === 'a' && L.listJoin(['a', 'b']) === 'a and b' &&
   L.listJoin(['a', 'b', 'c']) === 'a, b and c', 'listJoin');
ok(JSON.stringify(L.compactRanges([0, 15, 30, 45])) === '["0","15","30","45"]' &&
   JSON.stringify(L.compactRanges([9, 10, 11, 12])) === '["9-12"]', 'compactRanges');
ok(L.formatRelative(D(2026, 10, 14, 12, 0), D(2026, 10, 14, 12, 45)) === 'in 45m',
   'relative minutes');
ok(L.formatRelative(D(2026, 10, 14, 12, 0), D(2026, 10, 15, 14, 30)) === 'in 1d 2h',
   'relative days+hours');
ok(/Oct 15, 2026 at 02:00/.test(L.formatDateTime(D(2026, 10, 15, 2, 0))),
   'formatDateTime');
const txt = L.textSummary(L.parseCron('0 2 * * *'), D(2026, 10, 14, 12, 0),
  L.nextRuns(L.parseCron('0 2 * * *'), D(2026, 10, 14, 12, 0), 2));
ok(txt.includes('Cron: 0 2 * * *') && txt.includes('At 02:00.') &&
   (txt.match(/^- /gm) || []).length === 2, 'textSummary shape');

console.log('\n' + passed + ' passed, ' + failed + ' failed');
process.exit(failed ? 1 : 0);
