/*
 * test.js — unit tests for DecodeX' pure logic.
 * Run: node test.js
 *
 * The logic lives in the FIRST <script> block of index.html and is
 * browser-free, so we extract it, run it in a VM sandbox, and assert
 * against the exported __errLogic surface.
 */
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');

function countTag(tag) {
  const re = new RegExp('<' + tag + '[\\s>]', 'g');
  return (html.match(re) || []).length;
}
let passed = 0, failed = 0;
function ok(cond, name) {
  if (cond) { passed++; console.log('  ok - ' + name); }
  else { failed++; console.error('  FAIL - ' + name); }
}

// 1. document sanity
ok(countTag('html') === 1, 'single <html>');
ok(countTag('body') === 1, 'single <body>');
ok((html.match(/<\/script>/g) || []).length === 2, 'two script blocks (logic + UI)');
ok(html.includes('id="q"') && html.includes('id="go"') &&
   html.includes('id="out"') && html.includes('id="chips"'),
   'key element ids present');
ok(!/Built by Muse|Muse AI|generated by|AI assistant|anthropic/i.test(html), 'no AI attribution in html');

// 2. extract the logic script and run it in a sandbox
const m = html.match(/<script>([\s\S]*?)<\/script>/);
if (!m) { console.error('FAIL: no logic script block found'); process.exit(1); }
const sandbox = { console };
vm.createContext(sandbox);
vm.runInContext(m[1], sandbox);
const L = sandbox.__errLogic;
ok(!!L, 'logic exported as __errLogic');
ok(Array.isArray(L.DB) && L.DB.length >= 100, 'DB has >= 100 entries (got ' + (L.DB && L.DB.length) + ')');

// every entry has required fields
const cats = new Set(L.CATS.map(c => c.id));
let bad = [];
for (const e of L.DB) {
  if (!e.key || !e.code || !e.title || !e.cat || !e.sev || !e.meaning ||
      !Array.isArray(e.causes) || !e.causes.length ||
      !Array.isArray(e.steps) || !e.steps.length) bad.push(e.key || e.code);
  if (!cats.has(e.cat)) bad.push('bad-cat:' + e.key);
  if (!['info','warning','error','critical'].includes(e.sev)) bad.push('bad-sev:' + e.key);
}
ok(bad.length === 0, 'all entries have required fields (bad: ' + bad.slice(0,5).join(',') + ')');

// keys unique
const keys = L.DB.map(e => e.key);
ok(new Set(keys).size === keys.length, 'entry keys unique');

// 3. lookup — HTTP
ok(L.lookup('404').title === 'Not Found', 'lookup 404');
ok(L.lookup('  503 ').title === 'Service Unavailable', 'lookup trims whitespace');
ok(L.lookup('Error 401').title === 'Unauthorized', 'lookup strips "Error" prefix');
ok(L.lookup('HTTP 429').title === 'Too Many Requests', 'lookup strips "HTTP" prefix');

// 4. lookup — Windows HRESULT / Win32
ok(L.lookup('0x80070005').title.includes('E_ACCESSDENIED'), 'lookup 0x80070005 (lowercase hex)');
ok(L.lookup('0X80070005').title.includes('E_ACCESSDENIED'), 'lookup 0X80070005 (uppercase X)');
ok(L.lookup('80070005').title.includes('E_ACCESSDENIED'), 'lookup hex without 0x prefix');
ok(L.lookup('-2147024891').title.includes('E_ACCESSDENIED'), 'lookup signed-decimal HRESULT');
ok(L.lookup('5').title.includes('ERROR_ACCESS_DENIED'), 'bare "5" resolves to Win32 5');

// 5. lookup — POSIX / SMTP / DNS / JS
ok(L.lookup('EACCES').code === 'EACCES', 'lookup EACCES');
ok(L.lookup('econnrefused').title === 'Connection refused', 'lookup lowercase econnrefused');
ok(L.lookup('550').title.includes('Mailbox unavailable (permanent)'), 'lookup 550 → SMTP');
ok(L.lookup('NXDOMAIN').title.includes('domain does not exist'), 'lookup NXDOMAIN');
ok(L.lookup('ERR_NAME_NOT_RESOLVED').code === 'ERR_NAME_NOT_RESOLVED', 'lookup chrome err code');
ok(L.lookup('Failed to fetch').title.includes('Failed to fetch'), 'lookup "Failed to fetch" phrase');

// 6. unknown codes
ok(L.lookup('999') === null, 'lookup 999 → null');
ok(L.lookup('0xDEADBEEF') === null, 'lookup unknown hex → null');
ok(L.lookup('') === null, 'lookup empty → null');

// 7. decodeHresult bit layout
const h1 = L.decodeHresult('0x80070005');
ok(h1 && h1.severityText === 'FAILURE', '0x80070005 severity FAILURE');
ok(h1 && h1.facility === 7, '0x80070005 facility 7');
ok(h1 && h1.facilityText === 'FACILITY_WIN32', '0x80070005 facility name FACILITY_WIN32');
ok(h1 && h1.code === 5, '0x80070005 code 5');
ok(h1 && h1.win32Mapped && h1.win32Mapped.title.includes('ERROR_ACCESS_DENIED'),
   '0x80070005 maps to Win32 5 entry');
const h2 = L.decodeHresult('0xC0000005');
ok(h2 && h2.facilityText !== 'FACILITY_WIN32', '0xC0000005 facility is not WIN32');
ok(h2 && h2.code === 5 && h2.win32Mapped === null, '0xC0000005 code 5, no win32 mapping');
const h3 = L.decodeHresult('0x00000000');
ok(h3 && h3.severityText === 'SUCCESS', '0x00000000 severity SUCCESS');
ok(L.decodeHresult('not a code') === null, 'decodeHresult rejects garbage');
ok(L.facilityName(7) === 'FACILITY_WIN32', 'facilityName(7)');
ok(L.facilityName(999).includes('undocumented'), 'facilityName unknown → undocumented');

// 8. search
const s1 = L.search('access denied');
ok(s1.length > 0 && s1[0].score >= 60, 'search "access denied" finds strong hits');
const s2 = L.search('404');
ok(s2[0].entry.key === 'http:404', 'search "404" top hit is http:404');
const s3 = L.search('mailbox', 'smtp');
ok(s3.length > 0 && s3.every(r => r.entry.cat === 'smtp'), 'category filter restricts to smtp');
const s4 = L.search('zzz-no-such-code');
ok(s4.length === 0, 'search nonsense → no results');
const s5 = L.search('timeout');
ok(s5.some(r => r.entry.key === 'http:408' || r.entry.key === 'posix:etimedout'),
   'search "timeout" surfaces 408/ETIMEDOUT');

// 9. ticketText
const t = L.ticketText(L.lookup('404'), '404');
ok(t.includes('404') && t.includes('Not Found') && t.includes('Likely causes'),
   'ticketText contains code, title, causes');

// 10. no duplicate display codes within a category (ambiguous UX check)
const seen = {};
let dupes = [];
for (const e of L.DB) {
  const k = e.cat + '|' + e.code.toLowerCase();
  if (seen[k]) dupes.push(k); else seen[k] = 1;
}
ok(dupes.length === 0, 'no duplicate display codes within a category (dupes: ' + dupes.slice(0,3).join(',') + ')');

console.log('\n' + passed + ' passed, ' + failed + ' failed');
process.exit(failed ? 1 : 0);
