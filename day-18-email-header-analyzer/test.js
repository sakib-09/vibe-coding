/*
 * test.js — unit tests for MailTrail's pure logic.
 * Run: node test.js
 *
 * The logic lives in the FIRST <script> block of index.html and is
 * browser-free, so we extract it, run it in a VM sandbox with stubbed
 * browser globals, and assert against the exported __mhaLogic surface.
 */
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');

// 1. basic document sanity: tags that must exist exactly once / be balanced
function countTag(tag) {
  const re = new RegExp('<' + tag + '[\\s>]', 'g');
  return (html.match(re) || []).length;
}
let passed = 0, failed = 0;
function ok(cond, name) {
  if (cond) { passed++; console.log('  ok - ' + name); }
  else { failed++; console.error('  FAIL - ' + name); }
}

ok(countTag('html') === 1, 'single <html>');
ok(countTag('body') === 1, 'single <body>');
ok((html.match(/<\/script>/g) || []).length === 2, 'two script blocks (logic + UI)');
ok(html.includes('id="hdrInput"') && html.includes('id="analyzeBtn"') &&
   html.includes('id="results"') && html.includes('id="verdictBox"') &&
   html.includes('id="hopRows"') && html.includes('id="checkList"'),
   'key element ids present');
ok(!/Built by Muse|Muse AI|generated by|AI assistant|anthropic/i.test(html), 'no AI attribution in html');

// 2. extract the logic script and run it in a sandbox
const m = html.match(/<script>([\s\S]*?)<\/script>/);
if (!m) { console.error('FAIL: no logic script block found'); process.exit(1); }

const sandbox = {
  console,
  document: { addEventListener() {}, getElementById() { return null; } },
  localStorage: { getItem() { return null; }, setItem() {} },
  navigator: {}
};
vm.createContext(sandbox);
vm.runInContext(m[1], sandbox);
const L = sandbox.__mhaLogic;
ok(!!L, 'logic exported as __mhaLogic');

// 3. header unfolding (RFC 5322 continuation lines)
const folded = 'Subject: hello\n world\nFrom: <a@x.com>\n\nbody here';
const unfolded = L.unfoldHeaders(folded);
ok(unfolded.length === 2 && unfolded[0].name === 'Subject' && unfolded[0].value === 'hello world',
   'folded continuation lines are unfolded');
ok(unfolded[1].value === '<a@x.com>', 'second header parsed');
ok(L.splitHeaderBlock('A: 1\n\nB: 2') === 'A: 1', 'body is split off from headers');

// 4. RFC 2047 encoded words
ok(L.decodeWords('=?UTF-8?B?SGVsbG8gd29ybGQ=?=') === 'Hello world', 'B-encoded word decoded');
ok(L.decodeWords('plain subject') === 'plain subject', 'plain text untouched');
ok(L.decodeWords('=?UTF-8?Q?Caf=C3=A9?=') === 'Café', 'Q-encoded word decoded');

// 5. address extraction
const a1 = L.extractAddress('"Eftekar Buiya" <eftekar@example.org>');
ok(a1.address === 'eftekar@example.org' && a1.domain === 'example.org' && a1.name === 'Eftekar Buiya',
   'display-name <addr> parsed');
const a2 = L.extractAddress('bare.user@mail.example.com');
ok(a2.address === 'bare.user@mail.example.com' && a2.domain === 'mail.example.com' && a2.name === null,
   'bare address parsed');
const a3 = L.extractAddress('');
ok(a3.address === null && a3.domain === null, 'empty address -> nulls');

// 6. authentication-results parsing
const authRaw = 'Authentication-Results: mx.receiver.net;\n' +
  ' spf=pass (sender IP is 203.0.113.45) smtp.mailfrom=example.org;\n' +
  ' dkim=pass (signature was verified) header.d=example.org;\n' +
  ' dmarc=pass action=none header.from=example.org;';
const auth = L.parseAuthResults(L.unfoldHeaders(authRaw));
ok(auth.length === 1 && auth[0].server === 'mx.receiver.net', 'authserv-id parsed');
ok(auth[0].spf[0].result === 'pass' && auth[0].spf[0].domain === 'example.org', 'spf result+domain parsed');
ok(auth[0].dkim[0].domain === 'example.org', 'dkim header.d parsed');
ok(auth[0].dmarc[0].result === 'pass', 'dmarc result parsed');
const worst = L.summarizeAuth([{ result: 'pass' }, { result: 'fail' }]);
ok(worst.result === 'fail', 'worst auth result wins');
const mixed = L.summarizeAuth([{ result: 'neutral' }, { result: 'softfail' }]);
ok(mixed.result === 'softfail', 'softfail outranks neutral');

// 7. received parsing + delays
const r1 = L.parseReceived('from mail.example.org (mail.example.org [203.0.113.45]) by mx.receiver.net with ESMTPS id qrs456; Fri, 09 Oct 2026 14:22:48 -0600');
ok(r1.fromHost === 'mail.example.org' && r1.fromIp === '203.0.113.45', 'received from host+ip');
ok(r1.byHost === 'mx.receiver.net', 'received by host');
ok(typeof r1.date === 'number', 'received timestamp parsed');
const r2 = L.parseReceived('from [192.168.1.10] (unknown [203.0.113.45]) by mail.example.org; Fri, 09 Oct 2026 14:22:10 -0600');
ok(r2.fromHost === null && r2.fromIp === '203.0.113.45', 'bracketed IP: public ip from parens preferred');
ok(L.isPrivateIp('192.168.1.10') && L.isPrivateIp('10.0.0.5') && L.isPrivateIp('172.16.9.9') &&
   L.isPrivateIp('127.0.0.1') && !L.isPrivateIp('203.0.113.45'), 'private IP detection');
const hops = [
  { date: Date.parse('2026-10-09T14:23:02-06:00') },
  { date: Date.parse('2026-10-09T14:22:48-06:00') }
];
L.computeDelays(hops);
ok(hops[0].delaySec === 14, 'hop delay = 14s');
ok(L.formatDuration(14) === '14s' && L.formatDuration(3720) === '1h 2m' && L.formatDuration(90000) === '1d 1h',
   'duration formatting');

// 8. end-to-end: clean message -> pass verdict
const clean = [
  'From: "Eftekar Alom Buiya" <eftekar@example.org>',
  'To: Sakib Asad <asadsakib02@example.com>',
  'Subject: URBSA meeting this Friday',
  'Date: Fri, 09 Oct 2026 14:22:10 -0600',
  'Message-ID: <c3f9a1b2@mail.example.org>',
  'Return-Path: <eftekar@example.org>',
  'Authentication-Results: mx.receiver.net;',
  ' spf=pass (sender IP is 203.0.113.45) smtp.mailfrom=example.org;',
  ' dkim=pass (signature was verified) header.d=example.org;',
  ' dmarc=pass action=none header.from=example.org;',
  'Received: from mx.receiver.net (mx.receiver.net [198.51.100.7])',
  ' by final.receiver.net with ESMTP id xyz789; Fri, 09 Oct 2026 14:23:02 -0600',
  'Received: from mail.example.org (mail.example.org [203.0.113.45])',
  ' by mx.receiver.net with ESMTPS id qrs456; Fri, 09 Oct 2026 14:22:48 -0600'
].join('\n');
const ac = L.analyze(clean);
ok(ac.verdict === 'pass', 'clean message -> pass verdict');
ok(ac.summary.from.domain === 'example.org' && ac.summary.subject === 'URBSA meeting this Friday',
   'clean summary fields');
ok(ac.hops.length === 2 && ac.hops[0].delaySec === 14, 'clean hop chain + delay');
ok(ac.checks.some(c => c.level === 'pass' && /SPF passed/.test(c.title)), 'spf pass check present');

// 9. end-to-end: phishing message -> fail verdict with the right flags
const phish = [
  'From: "PayPal Security" <security@notice-paypal.com>',
  'Subject: Urgent: your account will be suspended',
  'Date: Sun, 11 Oct 2026 03:41:55 +0000',
  'Return-Path: <bounce@phish-attacker.net>',
  'Reply-To: "PayPal Support" <help@phish-attacker.net>',
  'Authentication-Results: mx.receiver.net;',
  ' spf=fail (sender IP is 198.51.100.99) smtp.mailfrom=phish-attacker.net;',
  ' dkim=fail (bad signature) header.d=notice-paypal.com;',
  ' dmarc=fail action=quarantine header.from=notice-paypal.com;',
  'Received: from webmail.phish-attacker.net (unknown [198.51.100.99])',
  ' by mx.receiver.net with ESMTP id evil002; Sun, 11 Oct 2026 03:41:55 +0000'
].join('\n');
const ap = L.analyze(phish);
ok(ap.verdict === 'fail', 'phishing message -> fail verdict');
ok(ap.checks.some(c => c.level === 'fail' && /SPF FAILED/.test(c.title)), 'spf fail flagged');
ok(ap.checks.some(c => c.level === 'fail' && /DKIM FAILED/.test(c.title)), 'dkim fail flagged');
ok(ap.checks.some(c => /Return-Path domain/.test(c.title)), 'from vs return-path mismatch flagged');
ok(ap.checks.some(c => /Reply-To goes somewhere else/.test(c.title)), 'reply-to mismatch flagged');
ok(ap.checks.some(c => /No Message-ID/.test(c.title)), 'missing message-id noted');

// 10. no auth headers -> warn, not fail
const noauth = L.analyze('From: <a@x.com>\nSubject: hi\n\nbody');
ok(noauth.verdict === 'warn', 'missing auth headers -> warn verdict');
ok(noauth.checks.some(c => /No Authentication-Results/.test(c.title)), 'missing auth check present');

// 11. text summary + html escaping
const txt = L.textSummary(ap);
ok(txt.includes('Verdict: Suspicious') && txt.includes('[FAIL]'), 'text summary has verdict + findings');
ok(L.escapeHtml('<script>alert(1)</script>') === '&lt;script&gt;alert(1)&lt;/script&gt;', 'html escaping');

console.log('\n' + passed + ' passed, ' + failed + ' failed');
process.exit(failed ? 1 : 0);
